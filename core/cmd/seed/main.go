// Command seed populates a running TroubaCore server with a demo dataset — users,
// bands, an orchestra, songs, sheet-music, and layered annotations — then prints a
// guide for browsing it.
//
// T134 phase 2 (stage C): each band is now seeded by building its CANONICAL v2 band
// directory (a demo group in memory from the Go literals; a real band by migrating
// its folder on read), packing it to a .tband, and POSTing it to the import endpoint
// — one path for the demo and real bands. Import FIRST, passwords SECOND (⟨P8⟩): the
// admin is registered as the importer, everyone else arrives via import (personal
// content intact) and is then given a password over the public reset flow. What a
// file cannot carry — passwords — is all that stays in the seeder.
//
// PDFs are read from docs/demo-charts (or generated as a fallback), so the seed never
// fails for lack of internet; a user/band that already exists is reused.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

func main() {
	addr := flag.String("addr", "http://localhost:8080", "base URL of the running troubacore server")
	password := flag.String("password", "demo", "password set for every demo user")
	only := flag.String("only", "", "seed only groups whose name contains this substring (case-insensitive), plus just their members; e.g. -only orchestra. Empty = seed everything.")
	var bands multiFlag
	flag.Var(&bands, "band", "seed only the local band(s) (bands/*/band.json) whose shortname matches; repeatable, e.g. -band myband -band otherband. Used by `make band=<shortname>` (make splits a comma list into repeated -band flags).")
	dumpImports := flag.String("dump-imports", "", "write each demo chart's exact annotation import payload to this dir (offline, no server) and exit — provenance for docs/demo-charts/*.annotations.json (B13).")
	flag.Parse()

	if *dumpImports != "" {
		if err := runDumpImports(*dumpImports); err != nil {
			log.Fatalf("seed -dump-imports: %v", err)
		}
		return
	}

	if err := run(*addr, *password, *only, bands); err != nil {
		log.Fatalf("seed: %v", err)
	}
}

// multiFlag collects a repeatable string flag (e.g. -band myband -band otherband) into a slice.
// Each occurrence is one value — commas are NOT split, so `-band otherband,myband` stays a single
// (unmatched) shortname rather than silently meaning two bands.
type multiFlag []string

func (m *multiFlag) String() string { return strings.Join(*m, ",") }
func (m *multiFlag) Set(v string) error {
	*m = append(*m, v)
	return nil
}

// runDumpImports builds every demo chart's annotation import offline (placeholder ids + the
// committed anchor manifests) and writes <chart>.annotations.json — the provenance source for
// the tracked docs, never hand-edited (B13 §6).
func runDumpImports(dir string) error {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	u := map[string]string{"marie": "marie", "leo": "leo", "sasha": "sasha", "ivan": "ivan", "cory": "cory", "flora": "flora"}
	note := "GENERATED by `go run ./cmd/seed -dump-imports` from the cmd/seed builders + " +
		"docs/demo-charts/*.anchors.json (B13). Do NOT hand-edit — regenerate. Coords are page-" +
		"relative [0,1]; ids are the seed's stable derivations. This is the exact payload the seed " +
		"POSTs to .../annotations/import."
	type doc struct {
		Note    string       `json:"//"`
		Layers  []wireLayer  `json:"layers"`
		Objects []wireObject `json:"objects"`
	}
	charts := []struct {
		name string
		im   annotationsImport
	}{
		{"open-road", buildOpenRoadAnnotations("open-road", "leadsheet", u, "leo", mustAnchors("open-road-leadsheet"))},
		{"open-road-guitar", buildOpenRoadGuitarAnnotations("open-road", "guitar", u, "leo", mustAnchors("open-road-guitar"))},
		{"house-rising-sun-tab", buildBandChartAnnotations("house", "tab", "House of the Rising Sun", u, "leo", mustAnchors("house-rising-sun-tab"))},
		{"house-rising-sun-drums", buildDrumPartAnnotations("house", "drums", mustAnchors("house-rising-sun-drums"))},
		{"amazing-grace", buildBandChartAnnotations("grace", "ls", "Amazing Grace", u, "leo", mustAnchors("amazing-grace"))},
		{"greensleeves", buildBandChartAnnotations("greensleeves", "gs", "Greensleeves", u, "leo", mustAnchors("greensleeves"))},
		{"ek-violin1", buildEineKleineAnnotations("ek", "vln1", u, "flora", mustAnchors("ek-violin1"))},
		{"ek-score", buildScoreConductorAnnotations("ek", "score", "ek", "flora", mustAnchors("ek-score"))},
		{"canon-violin1", buildCanonAnnotations("canon", "vln1", u, "flora", mustAnchors("canon-violin1"))},
		{"canon-score", buildScoreConductorAnnotations("canon", "score", "canon", "flora", mustAnchors("canon-score"))},
	}
	for _, c := range charts {
		b, err := json.MarshalIndent(doc{Note: note, Layers: c.im.Layers, Objects: c.im.Objects}, "", "  ")
		if err != nil {
			return err
		}
		p := filepath.Join(dir, c.name+".annotations.json")
		if err := os.WriteFile(p, append(b, '\n'), 0o644); err != nil {
			return err
		}
		fmt.Printf("wrote %s (%d layers, %d objects)\n", p, len(c.im.Layers), len(c.im.Objects))
	}
	return nil
}

// person is a demo user definition.
type person struct {
	username string
	display  string
	role     string // human-readable role label for the guide (instrument/part)
}

// songDef pairs a song title/artist + settable metadata with its PDF source(s).
//
// A song normally has one shared PDF (src). To showcase the multi-file /
// per-member "my files" feature, a song may instead define several pool files
// (files): each is uploaded to the shared pool with a distinct human title
// (pdfSource.docTitle). When files is set it takes precedence over src.
//
// myFilesFor curates a specific member's PERSONAL ordered selection over those
// pool files: keyed by username, the value is a list of indices into files in
// the exact order that member should see them (a non-default subset+order). The
// seeder PUTs this via the my-files endpoint as that user.
type songDef struct {
	title  string
	artist string
	// slug is the song's identity inside a LOCAL band folder (bands/<band>/<slug>/) — the key
	// setlists.json references (T100). Empty for demo songs, which have no folder.
	slug       string
	key        string // musical key (settable on the song page)
	tempo      int    // BPM
	meter      string // T86: metre "N/D" ("" = 4/4)
	tags       []string
	notes      string
	src        pdfSource
	files      []pdfSource      // optional multi-file shared pool (overrides src)
	myFilesFor map[string][]int // username -> ordered indices into files (custom my-files)
	// cuesFor seeds each member's PERSONAL song cues (T50): username -> that member's
	// ordered icon+color list. Self-only, so the seeder PUTs each list as that user;
	// they ride the member's per-member bake (visible when baking "my parts").
	cuesFor map[string][]cueDef
	// textCharts are folder-discovered chart parts (B15): each bands/<band>/<slug>/*.txt becomes a
	// text-chart part named after the file (lyrics.txt first, then sorted). Used by local bands;
	// demo songs use textChartPath below.
	textCharts []textPart // (textPart defined below)
	// textChartPath is an optional committed chart-dialect source (docs/demo-charts/*.chart)
	// added to the pool as a REAL text chart (T19) — POST /text-charts renders it to a PDF
	// server-side, so the demo shows the text-chart file type, not only uploaded PDFs (B10).
	textChartPath string
}

// textPart is one folder-discovered chart part (B15): a chart-dialect source file and the pool
// name it gets (the file's basename without .txt).
type textPart struct {
	path string
	name string
}

// cueDef is one personal song cue (T50): a curated glyph id + an optional "#rrggbb"
// tint ("" = neutral). See docs/tasks/T50-song-cues.md §2 for the id set.
type cueDef struct {
	icon  string
	color string
}

// overrideDef is a per-setlist-item override (settable on the setlist page).
type overrideDef struct {
	song            string // song title to match
	keyOverride     string
	tempoOverride   int
	notes           string
	onCall          bool // T100: mirrors .tband manifestItem.onCall
	transposeChords bool // T100: mirrors .tband manifestItem.transposeChords
}

// setlistDef is a setlist to create for a group, with optional item overrides.
type setlistDef struct {
	name      string
	eventDate string // ISO yyyy-mm-dd
	venue     string
	notes     string
	overrides []overrideDef
	// items is an EXPLICIT, ORDERED item list (T100 — a local band's setlists.json). When set it
	// replaces "every song the group has, in group order": a gig is a SUBSET in a chosen order, and
	// each entry may carry the same overrides. Empty ⇒ the demo behaviour, unchanged.
	items []overrideDef
}

// groupDef is a band or orchestra to create.
type groupDef struct {
	name      string
	kind      string // "Band" or "Orchestra" (label only)
	admin     string // username of the admin/owner
	members   []string
	conductor string // optional: a member to promote to the "conductor" role
	songs     []songDef
	setlists  []setlistDef
	// personal marks a REAL (non-demo) band (discovered from bands/*/band.json) that must stay
	// OUT of the public demo seed: it is skipped by a plain `seed`/`make demo` run and only built
	// when explicitly selected (`-only <name>` or `-band <shortname>`). Its members are likewise
	// registered only then.
	personal bool
	// shortname is the band.json "shortname" — a stable handle for `make band=<shortname>`.
	shortname string
	// folderPath is a local band's on-disk directory (T134 phase 2): the seeder migrates it on read
	// (legacy→canonical) → packs → imports, instead of driving the per-call REST sequence. "" for demo
	// groups, which build their canonical directory in memory from the Go literals (groupToCanonical).
	folderPath string
}


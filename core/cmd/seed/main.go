// troubaHome is the runtime root for non-repo data (T129), so live data does not live inside a git
// worktree where `git clean -xdf` can destroy it. TROUBA_HOME wins; else XDG_DATA_HOME/troubastack;
// else ~/.local/share/troubastack. Same formula as the Makefile — keep them in step.
func troubaHome() string {
	if h := os.Getenv("TROUBA_HOME"); h != "" {
		return h
	}
	// A visible ~/troubastack-data (VLL's call) rather than hiding live data deep in ~/.local/share:
	// this holds irreplaceable band libraries, and a folder people can see is a folder people back up.
	return filepath.Join(os.Getenv("HOME"), "troubastack-data")
}

// bandsDirCandidates is the ordered search for the local bands folder (T129). TROUBA_BANDS_DIR wins
// outright. Otherwise the runtime root comes FIRST, so a fresh checkout defaults OUT of the source
// tree; the historical cwd-relative paths follow, so an existing checkout with an in-tree bands/
// keeps working. Pure, so the ordering is unit-tested without touching the filesystem.
func bandsDirCandidates(bandsEnv, home string) []string {
	if bandsEnv != "" {
		return []string{bandsEnv}
	}
	return []string{filepath.Join(home, "bands"), "../bands", "bands", "../../bands", "../../../bands"}
}

func localBandsDir() string {
	for _, c := range bandsDirCandidates(os.Getenv("TROUBA_BANDS_DIR"), troubaHome()) {
		if fi, err := os.Stat(c); err == nil && fi.IsDir() {
			return c
		}
	}
	return ""
}

// bandManifest is a band folder's band.json (bands/<slug>/band.json).
type bandManifest struct {
	Name      string       `json:"name"`
	Shortname string       `json:"shortname"`
	Kind      string       `json:"kind"`
	Notes     string       `json:"notes"`
	Admin     bandMember   `json:"admin"`
	Members   []bandMember `json:"members"`
}
type bandMember struct {
	Username  string `json:"username"`
	Display   string `json:"display"`
	Role      string `json:"role"`
	Conductor bool   `json:"conductor,omitempty"` // promote this member to the app "conductor" role
	// Canonical v2 (T134 stage D): a rewritten folder has no `admin` block and no `display`/
	// `conductor` keys — `displayName` replaces `display`, `role` becomes the PERMISSION enum
	// (admin/conductor/member) and `plays` carries the instrument prose legacy put in `role`.
	// Read BOTH vocabularies here, keyed on the vocabulary and not on formatVersion: the stamp is
	// a claim about a folder, the keys are a fact about it.
	DisplayName string `json:"displayName,omitempty"`
	Plays       string `json:"plays,omitempty"`
}

// permissionRoles are the canonical `role` values. A legacy folder puts instrument prose in the
// same key, so a value outside this set is prose, not a permission.
var permissionRoles = map[string]bool{"admin": true, "conductor": true, "member": true}

// shown returns the member's display name in either vocabulary.
func (m bandMember) shown() string {
	if m.DisplayName != "" {
		return m.DisplayName
	}
	return m.Display
}

// plays returns what the member plays — `plays` canonically, or `role` when that key still holds
// prose (legacy). Never returns a permission enum, so a migrated band cannot end up with a member
// whose instrument reads "admin".
func (m bandMember) plays() string {
	if m.Plays != "" {
		return m.Plays
	}
	if m.Role != "" && !permissionRoles[m.Role] {
		return m.Role
	}
	return ""
}

// isConductor: legacy marks it with a bool, canonical with the role enum.
func (m bandMember) isConductor() bool { return m.Conductor || m.Role == "conductor" }

// adminUsername resolves the band admin in either vocabulary: the legacy `admin` block, else the
// member whose canonical role is "admin". Empty when neither names one.
func (b bandManifest) adminUsername() string {
	if b.Admin.Username != "" {
		return b.Admin.Username
	}
	for _, m := range b.Members {
		if m.Role == "admin" {
			return m.Username
		}
	}
	return ""
}

// selectGroups picks which groups to seed and narrows people to their members:
//
//	band != ""  → exactly the local band whose band.json shortname matches (make band=<shortname>)
//	only != ""  → groups whose name contains the substring (DEMO-VID seeds the orchestra only)
//	neither     → every DEMO group, but SKIP personal bands (they never enter the public demo)
//
// Returns an actionable error when a selector matches nothing. Pure (no I/O) so the demo-isolation
// property is unit-tested without a server.
func selectGroups(groups []groupDef, people []person, only string, bands []string) ([]groupDef, []person, error) {
	needle := strings.ToLower(only)
	// -band is repeatable — each occurrence names ONE band's shortname (make band=myband,otherband
	// splits the list into `-band myband -band otherband`). A stray comma stays part of the literal
	// shortname, so `-band otherband,myband` matches nothing and fails loud below.
	wantBands := map[string]bool{}
	for _, s := range bands {
		if s = strings.TrimSpace(s); s != "" {
			wantBands[s] = true
		}
	}
	bandMode := len(wantBands) > 0
	matchedBand := map[string]bool{}
	kept := groups[:0:0]
	keepUser := map[string]bool{}
	for _, g := range groups {
		var keep bool
		switch {
		case bandMode:
			keep = wantBands[g.shortname]
			if keep {
				matchedBand[g.shortname] = true
			}
		case only != "":
			keep = strings.Contains(strings.ToLower(g.name), needle)
		default:
			keep = !g.personal
		}
		if !keep {
			continue
		}
		kept = append(kept, g)
		keepUser[g.admin] = true
		for _, m := range g.members {
			keepUser[m] = true
		}
	}
	// Fail loud if any requested shortname matched nothing — seeding a partial set (myband
	// but not a mistyped "bnss") silently is a footgun. Names exactly which ones missed.
	if bandMode {
		var missing []string
		for s := range wantBands {
			if !matchedBand[s] {
				missing = append(missing, s)
			}
		}
		if len(missing) > 0 {
			sort.Strings(missing)
			return nil, nil, fmt.Errorf("seed: -band %q matched no band (check bands/*/band.json shortname)", strings.Join(missing, ","))
		}
	}
	if len(kept) == 0 {
		switch {
		case only != "":
			return nil, nil, fmt.Errorf("seed: -only %q matched no groups", only)
		default:
			return nil, nil, fmt.Errorf("seed: no groups to seed")
		}
	}
	filteredPeople := people[:0:0]
	for _, p := range people {
		if keepUser[p.username] {
			filteredPeople = append(filteredPeople, p)
		}
	}
	return kept, filteredPeople, nil
}

// loadLocalBands scans bands/*/band.json and returns one personal groupDef per band (with its
// folder-driven repertoire) plus the people it references. Missing folder → nothing (demo-only
// seed). This is the generic hook that lets any user seed their own band from a local folder.
func loadLocalBands() ([]groupDef, []person, error) {
	dir := localBandsDir()
	if dir == "" {
		return nil, nil, nil
	}
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, nil, err
	}
	var groups []groupDef
	var people []person
	seenUser := map[string]bool{}
	for _, e := range entries {
		if !e.IsDir() {
			continue
		}
		bandDir := filepath.Join(dir, e.Name())
		manPath := filepath.Join(bandDir, "band.json")
		raw, err := os.ReadFile(manPath)
		if err != nil {
			continue // a folder without band.json isn't a band
		}
		var man bandManifest
		if err := json.Unmarshal(raw, &man); err != nil {
			return nil, nil, fmt.Errorf("parse %s: %w", manPath, err)
		}
		shortname := man.Shortname
		if shortname == "" {
			shortname = e.Name() // fall back to the folder name
		}
		// The admin comes from either vocabulary (see adminUsername): a legacy `admin` block, or the
		// member whose canonical role is "admin". Still an error when neither names one.
		adminUser := man.adminUsername()
		if man.Name == "" || adminUser == "" {
			return nil, nil, fmt.Errorf("%s: name and an admin are required "+
				"(an \"admin\" block, or a member with \"role\": \"admin\")", manPath)
		}
		kind := man.Kind
		if kind == "" {
			kind = "Band"
		}
		addPerson := func(m bandMember) {
			if m.Username == "" || seenUser[m.Username] {
				return
			}
			seenUser[m.Username] = true
			people = append(people, person{username: m.Username, display: m.shown(), role: m.plays()})
		}
		addPerson(man.Admin) // legacy only; a canonical folder has no admin block (Username == "")
		memberNames := make([]string, 0, len(man.Members))
		conductor := ""
		for _, m := range man.Members {
			addPerson(m)
			// Canonical folders list the admin among members; legacy ones do not. Either way the
			// admin is carried separately, so it must not also appear in members.
			if m.Username != adminUser {
				memberNames = append(memberNames, m.Username)
			}
			if m.isConductor() {
				conductor = m.Username // who to promote (make band=…)
			}
		}
		songs, err := loadRepertoire(bandDir)
		if err != nil {
			return nil, nil, err
		}
		// T100: the band's concerts, if it defines any. Missing file ⇒ nil ⇒ seeds as before.
		setlists, err := loadSetlists(bandDir, songs)
		if err != nil {
			return nil, nil, err
		}
		groups = append(groups, groupDef{
			name: man.Name, kind: kind, admin: adminUser,
			members: memberNames, songs: songs, setlists: setlists, personal: true, shortname: shortname,
			conductor: conductor, folderPath: bandDir,
		})
	}
	return groups, people, nil
}

// loadSetlists reads <bandDir>/setlists.json into setlistDefs — a local band's concerts (T100).
//
// Shape mirrors the .tband manifest (app.manifestSetlist / manifestItem) so the hand-edited definition
// and the machine snapshot never fork a vocabulary: name, eventDate, venue, notes, and per-item
// keyOverride / tempoOverride / notes / onCall / transposeChords. Two deliberate deviations, both for
// hand-editing: `song` is a REPERTOIRE SLUG (not an internal songID), and ARRAY ORDER replaces an
// explicit `position`.
//
// A missing file is normal — the band seeds exactly as it did before. An unknown slug is a hard error
// naming the slug: silently dropping a song from a gig list is the worst thing this can do.
func loadSetlists(bandDir string, songs []songDef) ([]setlistDef, error) {
	path := filepath.Join(bandDir, "setlists.json")
	raw, err := os.ReadFile(path)
	if err != nil {
		if os.IsNotExist(err) {
			return nil, nil // no concerts defined: not an error
		}
		return nil, err
	}
	var doc struct {
		Setlists []struct {
			Name      string `json:"name"`
			EventDate string `json:"eventDate"`
			Venue     string `json:"venue"`
			Notes     string `json:"notes"`
			Items     []struct {
				Song            string `json:"song"` // a repertoire slug
				KeyOverride     string `json:"keyOverride"`
				TempoOverride   int    `json:"tempoOverride"`
				Notes           string `json:"notes"`
				OnCall          bool   `json:"onCall"`
				TransposeChords bool   `json:"transposeChords"`
			} `json:"items"`
		} `json:"setlists"`
	}
	if err := json.Unmarshal(raw, &doc); err != nil {
		return nil, fmt.Errorf("parse %s: %w", path, err)
	}
	titleBySlug := make(map[string]string, len(songs))
	for _, sd := range songs {
		if sd.slug != "" {
			titleBySlug[sd.slug] = sd.title
		}
	}
	out := make([]setlistDef, 0, len(doc.Setlists))
	for _, sl := range doc.Setlists {
		if strings.TrimSpace(sl.Name) == "" {
			return nil, fmt.Errorf("%s: a setlist has no name", path)
		}
		def := setlistDef{name: sl.Name, eventDate: sl.EventDate, venue: sl.Venue, notes: sl.Notes}
		for _, it := range sl.Items {
			title, ok := titleBySlug[it.Song]
			if !ok {
				// Loud, and it names the slug: a gig list that quietly loses a song is the failure
				// this task exists to prevent.
				return nil, fmt.Errorf("%s: setlist %q references unknown song slug %q (not in repertoire.json)", path, sl.Name, it.Song)
			}
			def.items = append(def.items, overrideDef{
				song: title, keyOverride: it.KeyOverride, tempoOverride: it.TempoOverride,
				notes: it.Notes, onCall: it.OnCall, transposeChords: it.TransposeChords,
			})
		}
		out = append(out, def)
	}
	return out, nil
}

// scorePriority ranks a source PDF for "full score first" ordering within a song:
//
//	0 = the full score (the whole arrangement — the sensible default part),
//	1 = an auxiliary sheet (lyrics/translation/gesture/booklet, or a doc exported to PDF),
//	2 = a single-instrument part (bass, drums, piano, guitar, …).
//
// Matched on the filename, case-insensitively, in French and English (the terms real band
// folders use). Anything with no telltale keyword is treated as the full score.
func scorePriority(path string) int {
	l := strings.ToLower(filepath.Base(path))
	partKeywords := []string{"bass", "basse", "drum", "batterie", "percussion",
		"piano", "guitar", "guitare", "flute", "flûte", "musicien"}
	for _, k := range partKeywords {
		if strings.Contains(l, k) {
			return 2
		}
	}
	auxKeywords := []string{"traduction", "paroles", "gestes", "livret", "lyrics", "resolution", ".docx"}
	for _, k := range auxKeywords {
		if strings.Contains(l, k) {
			return 1
		}
	}
	return 0
}

// loadRepertoire reads <bandDir>/repertoire.json into songDefs, attaching any real source PDFs
// the owner has dropped into <bandDir>/<slug>/. Missing file → no songs.
func loadRepertoire(bandDir string) ([]songDef, error) {
	path := filepath.Join(bandDir, "repertoire.json")
	raw, err := os.ReadFile(path)
	if err != nil {
		if os.IsNotExist(err) {
			return nil, nil
		}
		return nil, err
	}
	var rep struct {
		Songs []struct {
			Slug   string   `json:"slug"`
			Title  string   `json:"title"`
			Artist string   `json:"artist"`
			Key    string   `json:"key"`
			Tempo  int      `json:"tempo"`
			Meter  string   `json:"meter"` // T86: the real band-directory entry point; drop it here and a metre vanishes silently
			Notes  string   `json:"notes"`
			Tags   []string `json:"tags"`
		} `json:"songs"`
	}
	if err := json.Unmarshal(raw, &rep); err != nil {
		return nil, fmt.Errorf("parse %s: %w", path, err)
	}
	out := make([]songDef, 0, len(rep.Songs))
	for _, s := range rep.Songs {
		if s.Title == "" {
			continue
		}
		sd := songDef{title: s.Title, artist: s.Artist, key: s.Key, tempo: s.Tempo, meter: s.Meter, tags: s.Tags, notes: s.Notes, slug: s.Slug}
		if s.Slug != "" {
			pdfs, _ := filepath.Glob(filepath.Join(bandDir, s.Slug, "*.pdf"))
			// Full score first: a song's default part should be the whole arrangement, not a
			// single-instrument or lyrics-only sheet. Rank by scorePriority (score < aux < part),
			// then alphabetically within a rank so the order is stable.
			sort.SliceStable(pdfs, func(i, j int) bool {
				pi, pj := scorePriority(pdfs[i]), scorePriority(pdfs[j])
				if pi != pj {
					return pi < pj
				}
				return pdfs[i] < pdfs[j]
			})
			for _, p := range pdfs {
				base := strings.TrimSuffix(filepath.Base(p), filepath.Ext(p))
				sd.files = append(sd.files, pdfSource{localPath: p, docTitle: base, title: s.Title, subtitle: s.Artist})
			}
			// B15: every <slug>/*.txt (chart-dialect source) becomes its own text-chart part,
			// named after the file — lyrics.txt first (the song's default part), then the rest in
			// sorted order. So a folder can carry Lyrics + Guitar/Bass and reproduce both.
			txts, _ := filepath.Glob(filepath.Join(bandDir, s.Slug, "*.txt"))
			sort.Strings(txts)
			for _, p := range txts {
				if filepath.Base(p) == "lyrics.txt" {
					sd.textCharts = append([]textPart{{path: p, name: "lyrics"}}, sd.textCharts...)
				} else {
					sd.textCharts = append(sd.textCharts, textPart{path: p, name: strings.TrimSuffix(filepath.Base(p), ".txt")})
				}
			}
		}
		out = append(out, sd)
	}
	return out, nil
}


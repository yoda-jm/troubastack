// Package pdfmark draws the small "Made with TroubaStack" mark on EXPORTED PDFs (the concert print, the file
// print, the running order, the sound sheet) — T205. It is NEVER used by chartpdf: generated charts are the
// source the bake rasterizes for the tablets, so marking them would churn every page's raster hash and put
// branding on the stage display.
//
// Each renderer wires Draw through fpdf's SetFooterFunc, so the mark lands on EVERY page. The text and position
// are static (no timestamp, no measurement that varies with input), so output stays byte-deterministic.
package pdfmark

import "github.com/go-pdf/fpdf"

// DefaultText is the mark. It is a product word — see the docs-stage label list (VLL's words were "Generated by
// TroubaStack"). Kept here as the single source so every renderer prints the same string.
const DefaultText = "Made with TroubaStack"

// Draw places the muted mark at the bottom-right of the CURRENT page, below the renderer's own footer and
// inside the page's bottom margin. It is a no-op when show is false. Intended to be called from a
// SetFooterFunc, which fpdf invokes once per page.
func Draw(pdf *fpdf.Fpdf, show bool) {
	if !show {
		return
	}
	pw, ph := pdf.GetPageSize()
	lm, _, rm, _ := pdf.GetMargins()
	pdf.SetFont("Helvetica", "", 6.5)
	pdf.SetTextColor(150, 150, 150) // muted grey
	// Absolute position: a thin band 5.5mm up from the page bottom, right-aligned across the content width. The
	// renderers' own footers sit higher (above the bottom margin), so the mark never overlaps them.
	pdf.SetXY(lm, ph-5.5)
	pdf.CellFormat(pw-lm-rm, 4, DefaultText, "", 0, "R", false, 0, "")
	pdf.SetTextColor(0, 0, 0) // restore for any later drawing on the page
}
